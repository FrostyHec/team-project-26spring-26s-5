class DocumentAnalysisWidgetData(WidgetData):
    """Payload for the document analysis widget."""

    widget_type: Literal[WidgetType.DOCUMENT_ANALYSIS] = WidgetType.DOCUMENT_ANALYSIS
    summary: str = ""
    key_points: list[str] = Field(default_factory=list)
    difficult_concepts: list[str] = Field(default_factory=list)
    suggested_topics: list[str] = Field(default_factory=list)
    doc_type: str = "text"
    original_length: int = 0


