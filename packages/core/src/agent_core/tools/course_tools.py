def _read_pdf(path: str) -> str:
    """Read PDF file and extract text."""
    from pypdf import PdfReader

    reader = PdfReader(path)
    text_parts = []
    for page in reader.pages:
        text_parts.append(page.extract_text() or "")
    return "\n\n".join(text_parts)


def _read_docx(path: str) -> str:
    """Read Word document and extract text."""
    from docx import Document

    doc = Document(path)
    text_parts = []
    for paragraph in doc.paragraphs:
        if paragraph.text.strip():
            text_parts.append(paragraph.text)
    return "\n\n".join(text_parts)


def _read_pptx(path: str) -> str:
    """Read PowerPoint file and extract text."""
    from pptx import Presentation

    prs = Presentation(path)
    text_parts = []
    for slide in prs.slides:
        for shape in slide.shapes:
            if hasattr(shape, "text") and shape.text.strip():
                text_parts.append(shape.text)
    return "\n\n".join(text_parts)


def _read_xlsx(path: str) -> str:
    """Read Excel file and extract text."""
    from openpyxl import load_workbook

    wb = load_workbook(path, data_only=True)
    text_parts = []
    for sheet_name in wb.sheetnames:
        sheet = wb[sheet_name]
        text_parts.append(f"=== Sheet: {sheet_name} ===")
        for row in sheet.iter_rows(values_only=True):
            row_text = " | ".join(str(cell) if cell is not None else "" for cell in row)
            if row_text.strip():
                text_parts.append(row_text)
    return "\n".join(text_parts)


def _read_text_file(path: str) -> str:
    """Read plain text file."""
    with open(path, encoding="utf-8") as f:
        return f.read()


def _resolve_path(path: str) -> str:
    """Resolve a path to an absolute path, handling relative paths and ~ expansion."""
    if path.startswith("~"):
        path = os.path.expanduser(path)
    elif not os.path.isabs(path):
        # Detect absolute-looking paths that are missing the leading slash
        # (e.g., "Users/..." or "C:\Users\..." on Windows)
        if (
            path.startswith("Users/")
            or path.startswith("Program Files/")
            or path[1:3] == ":\\"
        ):
            # Likely an absolute path that lost its leading slash on Unix/Windows
            path = "/" + path
        else:
            # Resolve relative path from the project root (workspace directory)
            # course_tools.py is at: .../packages/core/src/agent_core/tools/course_tools.py  # noqa: E501
            # Need to go up 4 levels to reach the project root
            project_root = os.path.dirname(
                os.path.dirname(
                    os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
                )
            )
            path = os.path.normpath(os.path.join(project_root, path))
    if not os.path.isabs(path):
        path = os.path.normpath(os.path.abspath(path))
    else:
        path = os.path.normpath(path)
    return path


def _get_workspace_root() -> str:
    """Return the repository / workspace root directory.

    course_tools.py lives at
    ``<repo>/packages/core/src/agent_core/tools/course_tools.py``
    so we ascend 6 directory levels to reach the repo root.
    """
    here = os.path.abspath(__file__)
    for _ in range(6):
        here = os.path.dirname(here)
    return here


def _get_allowed_roots() -> list[str]:
    """Return the directories from which file reads are permitted.

    By default the workspace (repo) root and the OS temp directory are
    allowed.  Extra roots can be added via the ``COURSE_TOOLS_ALLOWED_ROOTS``
    environment variable (paths separated by ``os.pathsep``).
    """
    roots = [
        os.path.realpath(_get_workspace_root()),
        os.path.realpath(tempfile.gettempdir()),
    ]
    extra = os.environ.get("COURSE_TOOLS_ALLOWED_ROOTS", "")
    if extra:
        for entry in extra.split(os.pathsep):
            entry = entry.strip()
            if entry:
                roots.append(os.path.realpath(entry))
    return roots


def _validate_path(path: str) -> tuple[bool, str]:
    """Validate file path for security issues.

    The resolved real path must reside inside one of the allowed root
    directories (workspace root, temp dir, or any directory listed in
    the ``COURSE_TOOLS_ALLOWED_ROOTS`` env var).
    """
    if ".." in path:
        return False, "Path traversal not allowed"
    abs_path = _resolve_path(path)
    real_path = os.path.realpath(abs_path)
    allowed = _get_allowed_roots()
    if not any(
        real_path == root or real_path.startswith(root + os.sep) for root in allowed
    ):
        return False, "Access denied: path is outside allowed directories"
    if not os.path.exists(abs_path):
        return False, f"File not found: {path}"
    if not os.path.isfile(abs_path):
        return False, f"Not a file: {path}"
    file_size = os.path.getsize(abs_path)
    if file_size > MAX_FILE_SIZE:
        return False, f"File too large (max {MAX_FILE_SIZE // (1024 * 1024)}MB)"
    return True, ""


def read_file(path: str, doc_type: str = "auto") -> str:
    """Read a file and return its content as text.

    Supports various document formats. For unsupported formats,
    returns an error JSON with list of supported types.

    Args:
        path: File path (absolute or relative).
        doc_type: Document type hint. If "auto", detected from extension.
            Supported: txt, md, markdown, html, pdf, docx, pptx, xlsx

    Returns:
        File content as text, or error JSON if file cannot be read.
    """
    is_valid, error_msg = _validate_path(path)
    if not is_valid:
        return json.dumps({"error": error_msg})

    abs_path = _resolve_path(path)

    ext = os.path.splitext(abs_path)[1].lower()
    if doc_type != "auto":
        ext = f".{doc_type}"

    if ext not in SUPPORTED_EXTENSIONS:
        return json.dumps(
            {
                "error": "Unsupported file format",
                "supported_formats": sorted(SUPPORTED_EXTENSIONS),
                "your_format": ext,
            }
        )

    try:
        if ext in {".html", ".htm", ".txt", ".md", ".markdown"}:
            content = _read_text_file(abs_path)
        elif ext == ".pdf":
            content = _read_pdf(abs_path)
        elif ext == ".docx":
            content = _read_docx(abs_path)
        elif ext == ".pptx":
            content = _read_pptx(abs_path)
        elif ext == ".xlsx":
            content = _read_xlsx(abs_path)
        else:
            return json.dumps(
                {
                    "error": "Unsupported file format",
                    "supported_formats": sorted(SUPPORTED_EXTENSIONS),
                    "your_format": ext,
                }
            )

        return json.dumps(
            {
                "content": content,
                "format": ext,
                "path": path,
                "length": len(content),
            }
        )
    except Exception as e:
        return json.dumps({"error": f"Failed to read file: {str(e)}"})


def register_course_tools(registry: ToolRegistry) -> None:
    """Register all course assistant tools with the given registry."""
    registry.add_tool(
        func=read_file,
        description=(
            "Read a file and extract its content as text. "
            "Supports: txt, md, markdown, html, pdf, docx, pptx, xlsx. "
            "Returns JSON with content, format, path, and length. "
            "Args: path (str, required) — file path (absolute or relative); "
            "doc_type (str, optional, default 'auto') — hint for format, "
            "use 'auto' to detect from extension. "
            "Use this first when user provides a file path."
        ),
    )
    registry.add_tool(
        func=analyze_document,
        description=(
            "Format structured document analysis into a DocumentAnalysisWidget "
            "for frontend display. IMPORTANT: This does NOT analyze content — "
            "it ONLY formats already-generated analysis data into widget format. "
            "Args: summary (str, required) — 2-3 sentence overview of the document; "
            "key_points (list[str], required) — "
            "5-8 key knowledge points, one sentence each; "
            "difficult_concepts (list[str], optional) — "
            "3-5 concepts students often find confusing; "
            "suggested_topics (list[str], optional) — 3-5 follow-up study topics; "
            "doc_type (str, optional, default 'text') — "
            "document type (text/markdown/pdf/slides); "
            "original_length (int, optional, default 0) — "
            "original content length in characters. "
            "Call this after you have analyzed the material "
            "and generated the analysis data. "
            "Returns DocumentAnalysisWidgetData JSON "
            "that triggers the frontend analysis panel."
        ),
    )
    registry.add_tool(
        func=generate_quiz,
        description=(
            "Generate and display an interactive quiz widget in the sidebar panel. "
            "This tool takes your question data and renders it as an interactive quiz. "
            "Args: questions_json (str, required) — JSON array of question objects; "
            "quiz_title (str, optional) — title for the quiz panel; "
            "language (str, optional, default 'en') — 'en' or 'zh' for title. "
            "Each question object: {question (str), type (str), correct_answer (str), "
            "options (list[str], optional), explanation (str, optional)}. "
            "Type mapping: 'multiple_choice' = single choice with 4 options; "
            "'true_false' = provide 2 options, e.g. ['True', 'False']; "
            "'fill_blank' = fill-in-the-blank, question contains ___ as placeholder, "
            "answer is the word(s) that fill the blank, ONLY ONE blank allowed; "
            "'short_answer' = short answer question, no placeholder, "
            "answer is a concise response.\n"
            "For 'fill_blank': question text must contain ___, "
            "e.g. 'Python is a ___ language'; "
            "correct_answer is the word(s) to fill the blank, e.g. 'interpreted'.\n"
            "For 'short_answer': question is a complete question; "
            "correct_answer is a concise answer, e.g. 'Because it is concise'.\n"
            "For 'multiple_choice': correct_answer must be the FULL TEXT of "
            "the correct option, e.g. if options are ['Static typing', "
            "'Dynamic typing', 'Strong typing', 'Weak typing'], "
            "correct_answer must be 'Dynamic typing', NOT 'B' or '2'."
            "Returns QuizWidgetData JSON that triggers the frontend quiz panel."
        ),
    )
