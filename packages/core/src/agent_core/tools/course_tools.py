def generate_quiz(
    questions_json: str,
    quiz_title: str | None = None,
    language: str = "en",
) -> str:
    """Format quiz questions into QuizWidgetData for frontend display.

    Takes a JSON string containing quiz questions (generated by the LLM)
    and wraps it in QuizWidgetData format that triggers the frontend quiz panel.

    Args:
        questions_json: JSON string containing a list of quiz questions.
            Each question should have:
            - question (str): The question text
            - type (str): "multiple_choice" | "true_false" |
                "fill_blank" | "short_answer"
            - options (list[str], optional): For choice questions
            - correct_answer (str): The correct answer
            - explanation (str, optional): Explanation/answer outline
        quiz_title: Title for the quiz panel (default from prompts config,
            localized by language if not provided)
        language: Language code for localized default title (e.g., "en" or "zh")

    Returns:
        QuizWidgetData JSON that triggers the frontend quiz panel.

    Example:
        questions = (  # noqa: E501
            '[{"question": "What type system does Python use?", '
            '"type": "multiple_choice", '
            '"options": ["Static typing", "Dynamic typing", '
            '"Strong typing", "Weak typing"], '
            '"correct_answer": "Dynamic typing", '
            '"explanation": "Python determines types at runtime"}]'
        )
        result = generate_quiz(questions, "Python Basics Quiz")
    """
    # Use localized default title from prompts config if not provided
    if quiz_title is None:
        quiz_title = get_quiz_title(language)

    try:
        parsed = json.loads(questions_json)
    except (json.JSONDecodeError, TypeError):
        return json.dumps(
            {
                "error": "Invalid JSON format for questions",
                "hint": "Expected a JSON array of question objects, e.g.: "
                '[{"question": "...", "type": "multiple_choice", '
                '"options": [...], "correct_answer": "..."}]',
            }
        )

    if not isinstance(parsed, list):
        return json.dumps(
            {
                "error": "questions_json must be a JSON array of question objects",
            }
        )

    if len(parsed) == 0:
        return QuizWidgetData(
            title=quiz_title,
            questions=[],
            metadata={"error": "No questions provided"},
        ).model_dump_json()

    questions: list[QuizQuestion] = []
    errors: list[str] = []

    DEFAULT_SCORES = {
        "multiple_choice": 3.0,
        "true_false": 1.0,
        "fill_blank": 5.0,
        "short_answer": 10.0,
    }

    for i, q in enumerate(parsed):
        if not isinstance(q, dict):
            errors.append(f"Question {i + 1}: expected object, got {type(q).__name__}")
            continue

        q_type = q.get("type", "multiple_choice")
        valid_types = ("multiple_choice", "true_false", "fill_blank", "short_answer")
        if q_type not in valid_types:
            errors.append(
                f"Question {i + 1}: unknown type '{q_type}', using 'multiple_choice'"
            )
            q_type = "multiple_choice"

        raw_score = q.get("score")
        if raw_score is not None:
            try:
                score = float(raw_score)
            except (ValueError, TypeError):
                score = DEFAULT_SCORES.get(q_type, 10.0)
        else:
            score = DEFAULT_SCORES.get(q_type, 10.0)

        question_text = q.get("question", "")
        if not question_text:
            errors.append(f"Question {i + 1}: missing 'question' field")
            continue

        options = q.get("options")
        correct = q.get("correct_answer", "")
        if not correct:
            errors.append(f"Question {i + 1}: missing 'correct_answer' field")

        # Validate options for multiple_choice and true_false
        if q_type in ("multiple_choice", "true_false"):
            if not options or not isinstance(options, list) or len(options) < 2:
                errors.append(f"Question {i + 1}: {q_type} requires at least 2 options")
                continue
            if correct not in options:
                errors.append(
                    f"Question {i + 1}: correct_answer '{correct}' must be in options"
                )
                continue
        # For fill_blank and short_answer, options should be None
        elif q_type in ("fill_blank", "short_answer"):
            options = None

        questions.append(
            QuizQuestion(
                id=i + 1,
                type=q_type,
                question=question_text,
                options=options,
                correct_answer=correct,
                explanation=q.get("explanation"),
                score=score,
            )
        )

    if not questions:
        return json.dumps(
            {
                "error": "No valid questions found",
                "details": errors if errors else ["All questions failed validation"],
            }
        )

    metadata: dict[str, Any] = {
        "total_questions": len(questions),
        "quiz_type": _infer_quiz_type(questions),
    }
    if errors:
        metadata["warnings"] = errors

    return QuizWidgetData(
        title=quiz_title,
        questions=questions,
        show_answers=False,
        metadata=metadata,
    ).model_dump_json()


def _infer_quiz_type(questions: list[QuizQuestion]) -> str:
    """Infer the overall quiz type from question types."""
    types = {q.type for q in questions}
    if len(types) == 1:
        return types.pop()
    return "mixed"


def analyze_document(
    summary: str,
    key_points: list[str],
    difficult_concepts: list[str] | None = None,
    suggested_topics: list[str] | None = None,
    doc_type: str = "text",
    original_length: int = 0,
) -> str:
    """Format document analysis results into DocumentAnalysisWidgetData.

    Takes structured analysis data (generated by the LLM in the reasoning step)
    and wraps it in DocumentAnalysisWidgetData format for frontend display.

    Args:
        summary: Overall summary of the document content (2-3 sentences).
        key_points: List of 5-8 key knowledge points, each as a single sentence.
        difficult_concepts: List of 3-5 concepts that students often find confusing.
        suggested_topics: List of 3-5 suggested study topics for deeper learning.
        doc_type: Type of document (text, markdown, pdf, slides).
        original_length: Original length of the source content in characters.

    Returns:
        DocumentAnalysisWidgetData JSON that triggers the frontend widget.

    Example:
        result = analyze_document(  # noqa: E501
            summary=(
                "Python is a high-level programming language "
                "known for its clean syntax and powerful features."
            ),
            key_points=[
                "Python uses a dynamic type system",
                "Indentation determines code block structure",
                "Supports multiple programming paradigms",
            ],
            difficult_concepts=["Decorators", "Generators", "Context managers"],
            suggested_topics=[
                "Functional programming",
                "Object-oriented design",
                "Test-driven development",
            ],
            doc_type="slides",
            original_length=5000,
        )
    """
    if not summary:
        return DocumentAnalysisWidgetData(
            summary="No summary provided.",
            doc_type=doc_type,
            original_length=original_length,
        ).model_dump_json()

    return DocumentAnalysisWidgetData(
        summary=summary,
        key_points=key_points,
        difficult_concepts=difficult_concepts or [],
        suggested_topics=suggested_topics or [],
        doc_type=doc_type,
        original_length=original_length,
    ).model_dump_json()


